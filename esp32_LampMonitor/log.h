// ============================================================
// log.h — категорийное логирование
// ============================================================
// НОВЫЙ ФАЙЛ. Тонкая обёртка над Serial с разделением по категориям.
//
// Использование:
//   LOG(LOG_CAT_WIFI, "[WiFi] Подключение к \"%s\"...\n", ssid);
//   LOG_LN(LOG_CAT_MQTT, "[MQTT] Подключено");
//   LOG_ALWAYS("[ERR] Всё плохо\n");   // игнорирует маску, всегда печатает
//
// Категории и маска включения настраиваются в config.h.
// Если категория выключена, компилятор вырезает весь блок
// (внутри if с константным условием) — код не попадает в прошивку.
// ============================================================

#ifndef LOG_H
#define LOG_H

#include <Arduino.h>
#include "config.h"

// Проверка, включена ли категория. Макрос константный —
// оптимизатор сворачивает if и выкидывает ветку.
#define LOG_ENABLED(cat) ((LOG_ENABLED_CATEGORIES & (cat)) != 0)

// Основной макрос — как Serial.printf.
//   LOG(LOG_CAT_WIFI, "[WiFi] Скан: %d сетей\n", n);
#define LOG(cat, fmt, ...)                       \
    do {                                         \
        if (LOG_ENABLED(cat)) {                  \
            Serial.printf(fmt, ##__VA_ARGS__);   \
        }                                        \
    } while (0)

// Для строк без форматирования.
//   LOG_LN(LOG_CAT_MQTT, "[MQTT] Подключено");
#define LOG_LN(cat, msg)                         \
    do {                                         \
        if (LOG_ENABLED(cat)) {                  \
            Serial.println(msg);                 \
        }                                        \
    } while (0)

// Всегда печатается, вне зависимости от маски.
// Для действительно критичных вещей — например, провала init дисплея,
// когда лучше знать, что что-то сломалось, даже если логи отключены.
#define LOG_ALWAYS(fmt, ...) Serial.printf(fmt, ##__VA_ARGS__)

#endif