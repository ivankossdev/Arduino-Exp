#pragma once
#include <Arduino.h>

/* Абстрактный источник ввода.
 * .ino работает только с этим интерфейсом и не знает,
 * за ним кнопки, джойстик или акселерометр.
 *
 * Конкретный класс решает:
 *   - как физически читать устройство;
 *   - как превращать его в «шаги» (latch / порог / что угодно);
 *   - как определять переключение режима. */
class IInput {
public:
  enum Event {
    EV_NONE = 0,
    EV_MODE,      // запрос переключения режима (фронт)
    EV_UP,        // готов один шаг
    EV_DOWN,
    EV_LEFT,
    EV_RIGHT
  };

  virtual ~IInput() {}

  /* Настроить пины / I2C / что нужно. Вызывать в setup(). */
  virtual void begin() = 0;

  /* Опрос. Вызывать часто (100 Гц для кнопок, 30–50 Гц хватит для датчика).
   * Возвращает одно событие за вызов или EV_NONE. */
  virtual Event poll() = 0;

  /* Не выдавать событий направления, пока ввод не вернётся в «нейтраль»:
   *   кнопки      — все отпущены
   *   джойстик    — в центре
   *   акселерометр — выровнен
   * Нужно при возврате в MANUAL, чтобы зажатая кнопка / наклон
   * не дали «фантомный» шаг. */
  virtual void suppressUntilNeutral() = 0;
};